/**
 * TESTNET BOOTSTRAP — run ONCE to set up the corridor.
 *
 *   issuer ──issues USDC──> treasury (USD-side) ──settlement──> payout (PHP-side)
 *
 * Testnet has no fixed USDC issuer the way mainnet does, so we issue our own.
 * When it finishes, paste the output into .env. The testnet reset (2026-12-16)
 * wipes everything — at that point re-run this script and update .env + README.
 *
 * This file DELIBERATELY does not import src/stellar/config.ts: at bootstrap
 * time STELLAR_USDC_ISSUER is still empty, and importing it throws immediately
 * (chicken-and-egg).
 */
import 'dotenv/config'
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import {
  Asset,
  BASE_FEE,
  Horizon,
  Keypair,
  Networks,
  Operation,
  TransactionBuilder,
} from '@stellar/stellar-sdk'

// ─── Configuration ─────────────────────────────────────────────────────────

const NETWORK = (process.env.STELLAR_NETWORK ?? 'testnet').trim()
if (NETWORK !== 'testnet') {
  throw new Error(`STELLAR_NETWORK="${NETWORK}" — this script runs on testnet ONLY. Never run it on mainnet.`)
}

const DEFAULT_HORIZON = 'https://horizon-testnet.stellar.org'
const rawHorizon = (process.env.STELLAR_HORIZON_URL?.trim() || DEFAULT_HORIZON).replace(/\/+$/, '')
// Same reason as in src/stellar/config.ts: .env.example is missing the ".stellar" part.
const HORIZON_URL = new URL(rawHorizon).hostname === 'horizon-testnet.org' ? DEFAULT_HORIZON : rawHorizon

const ASSET_CODE = (process.env.STELLAR_ASSET_CODE?.trim() || 'USDC').toUpperCase()
const FRIENDBOT = 'https://friendbot.stellar.org'
/** Trustline limit + the amount issued to the treasury. */
const TRUST_LIMIT = '1000000.0000000'
const ISSUE_AMOUNT = '100000.0000000'
const FEE = String(Number(BASE_FEE) * 10)

const server = new Horizon.Server(HORIZON_URL)
const PASSPHRASE = Networks.TESTNET

// ─── Utilities ─────────────────────────────────────────────────────────────

const log = (...a: unknown[]) => console.log(...a)
const expert = (pk: string) => `https://stellar.expert/explorer/testnet/account/${pk}`

/**
 * Write the secrets to .env.secrets. Called RIGHT after generating the keypairs,
 * BEFORE any network call — on an earlier run friendbot died midway and all 3
 * secrets were lost because this function sat at the end of the script.
 */
function writeVault(issuer: Keypair, treasury: Keypair, payout: Keypair): string {
  // Every environment MUST have its own corridor: sharing one treasury between
  // production and local means racing for sequence numbers (the advisory lock is
  // per-database, so it does not block across environments), and every production
  // order would throw off the evidence pack's balance reconciliation. Set
  // BOOTSTRAP_VAULT to keep the secret files apart.
  const vaultPath = resolve(process.cwd(), process.env.BOOTSTRAP_VAULT ?? '.env.secrets')
  const vault = [
    '# Corridor account secrets — TESTNET ONLY.',
    `# Generated by bootstrap at ${new Date().toISOString()}`,
    '# This file is in .gitignore. DO NOT commit, DO NOT share.',
    '# The app does not read this file — it only signs with CORRIDOR_TREASURY_SECRET from .env.',
    '',
    `STELLAR_USDC_ISSUER=${issuer.publicKey()}`,
    `STELLAR_ISSUER_SECRET=${issuer.secret()}`,
    `CORRIDOR_TREASURY_PUBLIC=${treasury.publicKey()}`,
    `CORRIDOR_TREASURY_SECRET=${treasury.secret()}`,
    `CORRIDOR_PAYOUT_PUBLIC=${payout.publicKey()}`,
    `CORRIDOR_PAYOUT_SECRET=${payout.secret()}`,
    '',
  ].join('\n')
  writeFileSync(vaultPath, vault, { mode: 0o600 })
  return vaultPath
}

/** The network here is flaky; friendbot throws `fetch failed` rather than returning any HTTP. */
async function fetchRetry(url: string, tries = 5): Promise<Response> {
  let lastErr: unknown
  for (let i = 1; i <= tries; i++) {
    try {
      return await fetch(url)
    } catch (err) {
      lastErr = err
      const wait = 2000 * i
      log(`    (retry ${i}/${tries} in ${wait}ms — ${(err as Error)?.message ?? err})`)
      await new Promise((r) => setTimeout(r, wait))
    }
  }
  throw lastErr
}

async function fundWithFriendbot(publicKey: string, label: string): Promise<void> {
  const res = await fetchRetry(`${FRIENDBOT}?addr=${encodeURIComponent(publicKey)}`)
  if (!res.ok) {
    const body = await res.text().catch(() => '')
    // Friendbot returns 400 when the account already exists — not a fatal error.
    if (/already funded|op_already_exists/i.test(body)) {
      log(`  · ${label}: already on the ledger, skipping friendbot`)
      return
    }
    throw new Error(`Friendbot failed for ${label} (${res.status}): ${body.slice(0, 300)}`)
  }
  log(`  · ${label}: funded — ${publicKey}`)
}

/** Build + sign + submit, print the hash. Bootstrap is one-shot, so it needs no staged steps like settlement. */
async function submit(sourceKp: Keypair, buildOps: (b: TransactionBuilder) => TransactionBuilder, label: string) {
  const account = await server.loadAccount(sourceKp.publicKey())
  const tx = buildOps(new TransactionBuilder(account, { fee: FEE, networkPassphrase: PASSPHRASE }))
    .setTimeout(120)
    .build()
  tx.sign(sourceKp)
  const res = await server.submitTransaction(tx)
  log(`  · ${label}: ok — tx ${res.hash}`)
  return res
}

// ─── Run ───────────────────────────────────────────────────────────────────

async function main() {
  log(`\n=== TransPay bootstrap · Stellar TESTNET ===`)
  log(`Horizon : ${HORIZON_URL}`)
  log(`Asset   : ${ASSET_CODE}\n`)

  // 1. Three keypairs
  const issuer = Keypair.random()
  const treasury = Keypair.random()
  const payout = Keypair.random()
  log('[1/4] Generating keypairs')
  // Write the secrets BEFORE touching the network. Losing a secret to a network
  // failure permanently loses the ability to issue more USDC; writing first means
  // an interrupted run is still recoverable.
  log(`  · secrets written to ${writeVault(issuer, treasury, payout)} (chmod 600)`)
  log(`  · issuer   ${issuer.publicKey()}`)
  log(`  · treasury ${treasury.publicKey()}`)
  log(`  · payout   ${payout.publicKey()}`)

  // 2. Friendbot — sequential so the log stays readable, only 3 accounts
  log('\n[2/4] Funding with friendbot')
  await fundWithFriendbot(issuer.publicKey(), 'issuer')
  await fundWithFriendbot(treasury.publicKey(), 'treasury')
  await fundWithFriendbot(payout.publicKey(), 'payout')

  const asset = new Asset(ASSET_CODE, issuer.publicKey())

  // 3. Trustlines: without a trustline the payment fails with op_no_trust
  log(`\n[3/4] Trustline ${ASSET_CODE} → issuer`)
  await submit(treasury, (b) => b.addOperation(Operation.changeTrust({ asset, limit: TRUST_LIMIT })), 'treasury trustline')
  await submit(payout, (b) => b.addOperation(Operation.changeTrust({ asset, limit: TRUST_LIMIT })), 'payout trustline')

  // 4. The issuer issues USDC to the treasury
  log(`\n[4/4] Issuing ${ISSUE_AMOUNT} ${ASSET_CODE} to the treasury`)
  await submit(
    issuer,
    (b) => b.addOperation(Operation.payment({ destination: treasury.publicKey(), asset, amount: ISSUE_AMOUNT })),
    'issue',
  )

  // ─── Output ──────────────────────────────────────────────────────────────
  log('\n' + '─'.repeat(74))
  log('PASTE INTO .env:')
  log('─'.repeat(74))
  log(`STELLAR_NETWORK=testnet`)
  log(`STELLAR_HORIZON_URL=${HORIZON_URL}`)
  log(`STELLAR_ASSET_CODE=${ASSET_CODE}`)
  log(`STELLAR_USDC_ISSUER=${issuer.publicKey()}`)
  log(`CORRIDOR_TREASURY_SECRET=${treasury.secret()}`)
  log(`CORRIDOR_PAYOUT_PUBLIC=${payout.publicKey()}`)

  log('\n' + '─'.repeat(74))
  log('⚠  SECRETS ARE NOT IN .env — SAVE THEM SEPARATELY; LOSE THEM AND THEY ARE GONE FOREVER')
  log('─'.repeat(74))
  log(`CORRIDOR_PAYOUT_SECRET=${payout.secret()}`)
  log(`STELLAR_ISSUER_SECRET=${issuer.secret()}`)
  log('   The payout secret is needed to refund or to clean up the corridor.')
  log('   The issuer secret is needed to issue more USDC to the treasury.')
  log('   Neither may be committed and neither is needed to run the app — the app only signs with the treasury.')

  log('\n✓ The secrets are in .env.secrets (written back in step [1/4], chmod 600, gitignored).')

  log('\n' + '─'.repeat(74))
  log('Stellar Expert:')
  log('─'.repeat(74))
  log(`  issuer   ${expert(issuer.publicKey())}`)
  log(`  treasury ${expert(treasury.publicKey())}`)
  log(`  payout   ${expert(payout.publicKey())}`)
  log('')
}

main().catch((err) => {
  const extras = err?.response?.data?.extras
  console.error('\nBootstrap FAILED:', err?.message ?? err)
  if (extras) console.error('result_codes:', JSON.stringify(extras.result_codes))
  process.exit(1)
})
